/// Every fixed input is `BLAKE2s-256("rlmesh/v2 vector: " ‖ name)`.
fn fixed(name: &str) -> [u8; 32] {
    Blake2s256::digest(format!("rlmesh/v2 vector: {name}").as_bytes()).into()
}

/// Serves the given 32-byte values in order, then fails.
struct FixedRng(Vec<[u8; 32]>);

impl Rng for FixedRng {
    fn fill_bytes(&mut self, dest: &mut [u8]) -> Result<(), RngError> {
        if self.0.is_empty() || dest.len() != 32 {
            return Err(RngError);
        }
        dest.copy_from_slice(&self.0.remove(0));
        Ok(())
    }
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn unhex(v: &Value) -> Vec<u8> {
    let s = v.as_str().expect("a hex string");
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).expect("hex"))
        .collect()
}

fn unhex32(v: &Value) -> [u8; 32] {
    unhex(v).try_into().expect("32 bytes")
}

fn int(v: &Value) -> u64 {
    v.as_u64().expect("an integer")
}

fn text(v: &Value) -> &str {
    v.as_str().expect("a string")
}

fn lp(x: &[u8]) -> Vec<u8> {
    let mut out = u16::try_from(x.len())
        .expect("short")
        .to_le_bytes()
        .to_vec();
    out.extend_from_slice(x);
    out
}

/// snow with a fixed ephemeral and its own default DH and cipher, outside
/// `crypto`'s wrapper.
mod direct {
    use snow::params::{CipherChoice, DHChoice, HashChoice};
    use snow::resolvers::{CryptoResolver, DefaultResolver};
    use snow::types::{Cipher, Dh, Hash, Random};

    struct Once([u8; 32]);
    impl Random for Once {
        fn try_fill_bytes(&mut self, dest: &mut [u8]) -> Result<(), snow::Error> {
            dest.copy_from_slice(&self.0);
            Ok(())
        }
    }
    struct Fixed([u8; 32]);
    impl CryptoResolver for Fixed {
        fn resolve_rng(&self) -> Option<Box<dyn Random>> {
            Some(Box::new(Once(self.0)))
        }
        fn resolve_dh(&self, c: &DHChoice) -> Option<Box<dyn Dh>> {
            DefaultResolver.resolve_dh(c)
        }
        fn resolve_hash(&self, c: &HashChoice) -> Option<Box<dyn Hash>> {
            DefaultResolver.resolve_hash(c)
        }
        fn resolve_cipher(&self, c: &CipherChoice) -> Option<Box<dyn Cipher>> {
            DefaultResolver.resolve_cipher(c)
        }
    }

    pub fn builder(pattern: &str, ephemeral: [u8; 32]) -> snow::Builder<'static> {
        snow::Builder::with_resolver(
            pattern.parse().expect("pattern"),
            Box::new(Fixed(ephemeral)),
        )
    }

    pub fn write(hs: &mut snow::HandshakeState, payload: &[u8]) -> Vec<u8> {
        let mut buf = vec![0u8; 65_535];
        let n = hs.write_message(payload, &mut buf).expect("write");
        buf.truncate(n);
        buf
    }

    pub fn read(hs: &mut snow::HandshakeState, msg: &[u8]) -> Vec<u8> {
        let mut buf = vec![0u8; 65_535];
        let n = hs.read_message(msg, &mut buf).expect("read");
        buf.truncate(n);
        buf
    }
}

