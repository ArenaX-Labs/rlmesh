fn sealed_vector(encrypted: bool) -> Value {
    let name = if encrypted {
        "sealed encrypted key"
    } else {
        "sealed integrity key"
    };
    let key = fixed(name);
    let key_id = 0x0403_0201;
    let (kind, security, keyexpr, body): (Kind, Security, &str, &[u8]) = if encrypted {
        (
            Kind::CtlRequest,
            Security::Seal,
            "rlmesh/v2/acme/s/demo/p/arm-1/ctl",
            b"\x0a\x05hello attach",
        )
    } else {
        (
            Kind::ActionChunk,
            Security::Sign,
            "rlmesh/v2/acme/s/demo/d/7/cmd",
            b"\x08\x01\x12\x04\x00\x00\x80\x3f",
        )
    };
    let mut tx = SealSender::new(key_id, Key::from_bytes(key), KindSet::ALL, security);
    // Two messages first, so the vector's seq is 3.
    for _ in 0..2 {
        tx.seal(kind, keyexpr, b"").expect("seal");
    }
    let message = tx.seal(kind, keyexpr, body).expect("seal");
    json!({
        "inputs": { "key": name },
        "key": hex(&key),
        "key_id": key_id,
        "kind": kind.as_u8(),
        "seq": 3,
        "security": if encrypted { "seal" } else { "sign" },
        "encrypted": encrypted,
        "keyexpr": keyexpr,
        "body": hex(body),
        "message": hex(&message),
    })
}

fn signed_vector() -> Value {
    let secret = fixed("signed host ed25519 secret");
    let host_instance = 0x1122_3344_5566_7788;
    let keyexpr = "rlmesh/v2/acme/s/demo/host/state";
    let body = b"\x08\x2a\x10\x01authority state bytes";
    let mut tx = SignedSender::new(&secret, host_instance);
    for _ in 0..4 {
        tx.sign(
            SignedKind::VirtualTick,
            "rlmesh/v2/acme/s/demo/host/tick",
            b"",
        )
        .expect("sign");
    }
    let message = tx
        .sign(SignedKind::AuthorityState, keyexpr, body)
        .expect("sign");
    json!({
        "inputs": { "secret": "signed host ed25519 secret" },
        "secret": hex(&secret),
        "public": hex(&tx.verifying_key()),
        "host_instance": host_instance,
        "kind": SignedKind::AuthorityState.as_u8(),
        "seq": 5,
        "keyexpr": keyexpr,
        "body": hex(body),
        "message": hex(&message),
    })
}

/// IK through snow directly: msg 1, msg 2, `h` and the raw split.
#[allow(clippy::type_complexity)]
fn ik_direct(
    ps: &[u8; 32],
    host_static: &[u8; 32],
    pe: [u8; 32],
    he: [u8; 32],
    prologue: &[u8],
    accept: &[u8],
) -> (Vec<u8>, Vec<u8>, Vec<u8>, [u8; 32], [u8; 32]) {
    let host_public =
        x25519_dalek::PublicKey::from(&x25519_dalek::StaticSecret::from(*host_static)).to_bytes();
    let mut init = direct::builder(IK, pe)
        .local_private_key(ps)
        .and_then(|b| b.remote_public_key(&host_public))
        .and_then(|b| b.prologue(prologue))
        .and_then(|b| b.build_initiator())
        .expect("initiator");
    let mut resp = direct::builder(IK, he)
        .local_private_key(host_static)
        .and_then(|b| b.prologue(prologue))
        .and_then(|b| b.build_responder())
        .expect("responder");
    let msg1 = direct::write(&mut init, &[]);
    assert!(direct::read(&mut resp, &msg1).is_empty(), "msg 1 is empty");
    let msg2 = direct::write(&mut resp, accept);
    assert_eq!(direct::read(&mut init, &msg2), accept);
    let h = init.get_handshake_hash().to_vec();
    let (up, down) = init.dangerously_get_raw_split();
    assert_eq!(resp.dangerously_get_raw_split(), (up, down));
    (msg1, msg2, h, up, down)
}

const UP_KEY_ID: u32 = 7;
const DOWN_KEY_ID: u32 = 8;
const CTL: &str = "rlmesh/v2/acme/s/demo/ctl";

fn ik_vector() -> Value {
    let names = [
        "ik participant static",
        "ik host static",
        "ik participant ephemeral",
        "ik host ephemeral",
    ];
    let [ps, hs, pe, he] = names.map(fixed);
    let participant = StaticKeypair::from_private(ps);
    let host = StaticKeypair::from_private(hs);
    let (tenant, session, host_instance, name) =
        ("acme", "demo", 0x0102_0304_0506_0708u64, "arm-1");
    let prologue = handshake::prologue(tenant, session, host_instance, name).expect("prologue");
    // Any fixed bytes: the HandshakeAccept message is defined with the wiring.
    let accept = b"\x08\x01\x12\x06laptop\x18\x02";
    let (init, msg1) = IkInitiator::start(
        &mut FixedRng(vec![pe]),
        &participant,
        host.public(),
        &prologue,
    )
    .expect("msg1");
    let resp =
        IkResponder::read_request(&mut FixedRng(vec![he]), &host, &prologue, &msg1).expect("read");
    let (msg2, host_keys) = resp.accept(accept).expect("msg2");
    let (got, keys) = init.finish(&msg2).expect("finish");
    assert_eq!(got, accept);
    let h = *keys.handshake_hash();
    let (_, _, _, up, down) = ik_direct(&ps, &hs, pe, he, &prologue, accept);
    let (mut p_tx, _) = keys.into_participant(UP_KEY_ID, DOWN_KEY_ID);
    let (mut h_tx, _) = host_keys.into_host(UP_KEY_ID, DOWN_KEY_ID);
    let sealed_up = p_tx
        .seal(Kind::CtlRequest, CTL, b"\x0a\x06attach")
        .expect("seal");
    let sealed_down = h_tx.seal(Kind::CtlReply, CTL, b"\x08\x01").expect("seal");
    json!({
        "inputs": {
            "participant_static": names[0], "host_static": names[1],
            "participant_ephemeral": names[2], "host_ephemeral": names[3],
        },
        "participant_static_private": hex(&ps),
        "participant_static_public": hex(participant.public()),
        "host_static_private": hex(&hs),
        "host_static_public": hex(host.public()),
        "participant_ephemeral_private": hex(&pe),
        "host_ephemeral_private": hex(&he),
        "tenant": tenant,
        "session": session,
        "host_instance": host_instance,
        "participant": name,
        "prologue": hex(&prologue),
        "msg1": hex(&msg1),
        "accept": hex(accept),
        "msg2": hex(&msg2),
        "handshake_hash": hex(&h),
        "k_up": hex(&up),
        "k_down": hex(&down),
        "up_key_id": UP_KEY_ID,
        "down_key_id": DOWN_KEY_ID,
        "keyexpr": CTL,
        "sealed_up": hex(&sealed_up),
        "sealed_down": hex(&sealed_down),
    })
}

fn exchange_id() -> [u8; 16] {
    fixed("pair exchange")[..16].try_into().expect("16")
}

fn pairing_vector() -> Value {
    let names = [
        "pair laptop static",
        "pair daemon static",
        "pair laptop ephemeral",
        "pair daemon ephemeral",
        "pair nr",
        "pair ni",
    ];
    let [ls, ds, le, de, nr, ni] = names.map(fixed);
    let exchange = exchange_id();
    let laptop = StaticKeypair::from_private(ls);
    let daemon = StaticKeypair::from_private(ds);
    let (init, xx1) =
        PairInitiator::start(&mut FixedRng(vec![le]), &laptop, &exchange).expect("xx1");
    let (resp, xx2) =
        PairResponder::start(&mut FixedRng(vec![de]), &daemon, &exchange, &xx1).expect("xx2");
    let (mut l, xx3) = init.finish(&xx2).map_err(|(_, e)| e).expect("xx3");
    let mut d = resp.finish(&xx3).map_err(|(_, e)| e).expect("link");
    let h = *d.handshake_hash();
    assert_eq!(&h, l.handshake_hash());
    let mut commit = DaemonCommit::new(&mut FixedRng(vec![nr]), &h).expect("commit");
    let c = *commit.commitment().expect("c");
    let lap = LaptopCommit::new(&mut FixedRng(vec![ni]), &h, &c).expect("ni");
    let (revealed, daemon_sas) = commit.reveal(lap.nonce()).expect("reveal");
    let laptop_sas = lap.check_reveal(&revealed).expect("check");
    assert_eq!(laptop_sas, daemon_sas);
    // The split: one sealed message each way, opened in the cross-check
    // under keys taken from snow directly.
    let up = l
        .sender
        .seal(Kind::PairNonce, "rlmeshd/pair", lap.nonce())
        .expect("seal");
    let down = d
        .sender
        .seal(Kind::PairCommit, "rlmeshd/pair", &c)
        .expect("seal");
    json!({
        "inputs": {
            "laptop_static": names[0], "daemon_static": names[1],
            "laptop_ephemeral": names[2], "daemon_ephemeral": names[3],
            "nr": names[4], "ni": names[5], "exchange": "pair exchange",
        },
        "exchange": hex(&exchange),
        "prologue": hex(&pairing::prologue(&exchange)),
        "laptop_static_private": hex(&ls),
        "laptop_static_public": hex(laptop.public()),
        "daemon_static_private": hex(&ds),
        "daemon_static_public": hex(daemon.public()),
        "laptop_ephemeral_private": hex(&le),
        "daemon_ephemeral_private": hex(&de),
        "xx1": hex(&xx1),
        "xx2": hex(&xx2),
        "xx3": hex(&xx3),
        "h": hex(&h),
        "nr": hex(&nr),
        "ni": hex(&ni),
        "c": hex(&c),
        "sas": laptop_sas.value(),
        "sas_text": laptop_sas.to_string(),
        "keyexpr": "rlmeshd/pair",
        "sealed_pair_nonce": hex(&up),
        "sealed_pair_commit": hex(&down),
    })
}

