    #[test]
    fn undeclared_everywhere_is_the_old_highest_mutual() {
        fn highest_mutual(sets: &[&[String]]) -> Option<String> {
            let (first, rest) = sets.split_first()?;
            first
                .iter()
                .map(|value| value.trim())
                .filter(|value| !value.is_empty())
                .filter(|value| {
                    rest.iter()
                        .all(|set| set.iter().any(|other| other.trim() == *value))
                })
                .max_by_key(|value| super::edition_sort_key(value))
                .map(|value| value.to_string())
        }

        let shapes: &[&[&[&str]]] = &[
            &[&["2026.06"], &["2026.06"]],
            &[&["2026.01", " 2026.06 "], &["2026.06", "2026.01"]],
            &[&["2025.01", "2026.06", "2031.12"], &["2026.06"]],
            &[&["2026.11", "2027.01"], &["2026.06"]],
            &[&[""], &["2026.06"]],
            &[&[], &["2026.06"]],
            &[
                &["2026.06", "2026.08"],
                &["2026.06", "2026.08"],
                &["2026.06"],
            ],
            &[&["2026.08"], &["2026.08"], &["2026.06"]],
            &[
                &["2026.06", "2026.06-0.1.0-rc.1"],
                &["2026.06", "2026.06-0.1.0-rc.1"],
                &["2026.06", "2026.06-0.1.0-rc.1"],
            ],
            &[
                &["2026.06", "2026.06-dev.aaa"],
                &["2026.06", "2026.06-dev.bbb"],
                &["2026.06", "2026.06-dev.aaa"],
            ],
            &[&["2026.06"], &["2026.06", "2099.01"]],
        ];

        for shape in shapes {
            let offers: Vec<SessionOffer> = shape.iter().map(|can| tier(can, None)).collect();
            let owned: Vec<Vec<String>> = shape.iter().map(|can| offer(can)).collect();
            let sets: Vec<&[String]> = owned.iter().map(Vec::as_slice).collect();
            let borrowed: Vec<(&str, &SessionOffer)> = offers.iter().map(|o| ("tier", o)).collect();
            assert_eq!(
                super::select_workflow_edition(&borrowed).ok(),
                highest_mutual(&sets),
                "{shape:?}"
            );
        }
    }

