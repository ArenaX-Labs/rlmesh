"""Generate Rust Default assertions from the reviewed E-1 manifest.

Default and constructor fields are identified by the native Type#field parameter mappings.
Python literals are the reference; duplicate mappings must agree. None uses
is_none so callbacks and trait objects need neither PartialEq nor Debug.
Unsupported literals fail generation instead of silently omitting a field.
"""

from __future__ import annotations

import argparse
import ast
import json
import pathlib
import subprocess

import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "docs/specs/language-parity/manifest.toml"
OUTPUT = ROOT / "crates/rlmesh/tests/parity_defaults.rs"


def options_defaults(manifest):
    """Collect every mapped data default; skips require a manifest explanation."""
    options = {}
    for symbol, entry in manifest.items():
        if "parameters" not in entry:
            continue
        mappings = entry.get("rust", {}).get("params", {})
        for keyword, parameter in entry.get("parameters", {}).items():
            target = mappings.get(keyword, "")
            if "#" not in target:
                continue
            native_type, field = target.split("#")
            if "default" not in parameter:
                continue
            skips = entry.get("rust", {}).get("default_skip", {})
            if keyword in skips:
                if not skips[keyword].strip():
                    raise ValueError(
                        f"{symbol}.{keyword}: default_skip requires a reason (R-6)"
                    )
                continue
            if not native_type.rsplit("::", 1)[-1][:1].isupper():
                candidates = [
                    item.rsplit("::", 1)[0]
                    for item in entry["rust"].get("also", [])
                    if item.endswith(f"Options::{keyword}")
                ]
                if not candidates:
                    raise ValueError(
                        f"{symbol}.{keyword}: callable default needs rust.default_skip with a reason (R-7/R-12)"
                    )
                if len(candidates) != 1:
                    raise ValueError(f"ambiguous options field for {symbol}.{keyword}")
                native_type, field = candidates[0], keyword
            literal = ast.literal_eval(parameter["default"])
            fields = options.setdefault(native_type, {})
            if field in fields and (
                type(fields[field][2]) is not type(literal)
                or fields[field][2] != literal
            ):
                raise ValueError(f"conflicting defaults for {target}")
            fields.setdefault(field, (symbol, keyword, literal))
    if not options:
        raise ValueError("manifest maps no Rust options defaults")
    return options


def generate(manifest):
    """Render an assertion for every distinct mapped data-field Python default."""
    lines = [
        "// Generated by tests/parity/generate_defaults.py; do not edit.",
        "// Input: docs/specs/language-parity/manifest.toml.",
        "#[test]",
        "fn defaults_match_python_literals() {",
    ]
    for native_type, fields in options_defaults(manifest).items():
        constructors = {
            row.get("rust", {}).get("default_constructor")
            for symbol, row in manifest.items()
            if ":" in symbol
            and isinstance(row, dict)
            and any(
                target.startswith(native_type + "#")
                for target in row.get("rust", {}).get("params", {}).values()
            )
        } - {None}
        if len(constructors) > 1:
            raise ValueError(f"conflicting default_constructor for {native_type}")
        constructor = next(iter(constructors), native_type + "::default()")
        lines.append(f"    let value = {constructor};")
        for field, (symbol, keyword, literal) in fields.items():
            member = f"value.{field}"
            message = json.dumps(f"{symbol}.{keyword}")
            serializer = next(
                (
                    row.get("rust", {}).get("default_serializers", {}).get(keyword)
                    for path, row in manifest.items()
                    if path == symbol
                ),
                None,
            )
            if serializer == "json":
                assertion = f"assert_eq!(serde_json::to_value({member}).expect({message}), serde_json::json!({json.dumps(literal)}), {message});"
            elif serializer == "view_hold":
                if not isinstance(literal, bool):
                    raise ValueError(f"{symbol}.{keyword}: view_hold expects a bool")
                assertion = f"assert_eq!({member}, rlmesh::ViewHold::from({str(literal).lower()}), {message});"
            elif serializer:
                raise ValueError(
                    f"{symbol}.{keyword}: unknown default_serializers value {serializer!r}"
                )
            elif literal is None:
                assertion = f"assert!({member}.is_none(), {message});"
            elif isinstance(literal, bool):
                assertion = f"assert!({'' if literal else '!'}{member}, {message});"
            elif isinstance(literal, (int, float)):
                if keyword.endswith("_seconds"):
                    member += ".as_secs_f64()"
                    literal = float(literal)
                assertion = f"assert_eq!({member}, {literal!r}, {message});"
            elif isinstance(literal, str):
                assertion = f"assert_eq!({member}.to_string(), {json.dumps(literal)}, {message});"
            elif isinstance(literal, (list, tuple, dict)) and not literal:
                assertion = f"assert!({member}.is_empty(), {message});"
            elif isinstance(literal, (list, tuple)) and all(
                isinstance(item, (int, str)) for item in literal
            ):
                values = ", ".join(json.dumps(item) for item in literal)
                assertion = f"assert_eq!({member}, vec![{values}], {message});"
            else:
                raise ValueError(f"{symbol}.{keyword}: unsupported literal {literal!r}")
            lines.append("    " + assertion)
    lines.extend(["}", ""])
    return subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout"],
        input="\n".join(lines),
        text=True,
        capture_output=True,
        check=True,
    ).stdout


def main():
    """Write generated assertions, or check that they are current."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=pathlib.Path, default=MANIFEST)
    parser.add_argument("--output", type=pathlib.Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = generate(tomllib.loads(args.manifest.read_text()))
    if args.check:
        if args.output.read_text() != source:
            raise SystemExit(
                "Rust defaults test is stale; run tests/parity/generate_defaults.py"
            )
    else:
        args.output.write_text(source)


if __name__ == "__main__":
    main()
